// Generates src/styles/tokens.css from src/tokens/tokens.json.
// Run with `npm run tokens` (also runs automatically before `dev` and `build`).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'src/tokens/tokens.json');
const target = resolve(root, 'src/styles/tokens.css');

const tokens = JSON.parse(readFileSync(source, 'utf8'));

// Flatten palette groups (primary / secondary / states / neutral) into family -> steps,
// dropping metadata keys ($status) and steps Figma hasn't supplied a value for yet (null).
const families = {};
for (const group of Object.values(tokens.palette)) {
  for (const [family, scale] of Object.entries(group)) {
    if (families[family]) throw new Error(`Palette family "${family}" is defined in two groups`);
    families[family] = Object.fromEntries(
      Object.entries(scale).filter(([step, value]) => !step.startsWith('$') && value !== null),
    );
  }
}

// "neutral.900" -> var(--color-neutral-900); "neutral.900/10" -> 10% colour-mix.
function resolveRef(ref, name, mode) {
  const [path, alpha] = ref.split('/');
  const [family, step] = path.split('.');
  if (!families[family]?.[step]) {
    throw new Error(`semantic.${name}.${mode}: unknown palette token "${path}"`);
  }
  const value = `var(--color-${family}-${step})`;
  return alpha ? `color-mix(in srgb, ${value} ${alpha}%, transparent)` : value;
}

const primitives = Object.entries(families)
  .flatMap(([family, steps]) =>
    Object.entries(steps).map(([step, hex]) => `  --color-${family}-${step}: ${hex};`),
  )
  .join('\n');

const semantic = Object.entries(tokens.semantic);
const light = semantic.map(([n, t]) => `  --tabs-${n}: ${resolveRef(t.light, n, 'light')};`).join('\n');
const dark = semantic.map(([n, t]) => `  --tabs-${n}: ${resolveRef(t.dark, n, 'dark')};`).join('\n');
const utilities = semantic.map(([n]) => `  --color-${n}: var(--tabs-${n});`).join('\n');

// Text styles (imported from Figma) -> one utility per style, e.g. `type-heading-1`.
const typography = Object.entries(tokens.typography ?? {});
const typographyCss = typography.length
  ? `
/* Figma text styles -> type-* utilities (family, size, line height, tracking, weight). */
${typography
  .map(
    ([name, t]) => `@utility type-${name} {
  font-family: var(--font-${t.family});
  font-size: ${t.size};
  line-height: ${t.lineHeight};
  letter-spacing: ${t.letterSpacing};
  font-weight: ${t.weight};
}`,
  )
  .join('\n')}
`
  : '';

// Effect styles (imported from Figma) -> shadow-sm ... shadow-2xl, plus shadow-base.
const shadows = Object.entries(tokens.shadow ?? {});
const shadowCss = shadows.length
  ? `
/* Figma effect styles -> shadow-* utilities and var(--shadow-*). */
@theme static {
${shadows.map(([name, s]) => `  --shadow-${name}: ${s.value};`).join('\n')}
}
`
  : '';

const css = `/* GENERATED by scripts/build-tokens.mjs from src/tokens/tokens.json. Do not edit by hand. */

/* Palette primitives -> Tailwind utilities such as bg-tabs-blue-500, text-neutral-400. */
@theme static {
${primitives}
}

/* Semantic tokens. Use var(--tabs-*) in CSS. */
:root {
${light}
}

.dark {
${dark}
}

/* Semantic utilities such as bg-surface, text-fg, border-line (theme-aware). */
@theme inline {
${utilities}
}
${typographyCss}${shadowCss}`;

writeFileSync(target, css);
console.log(
  `tokens: wrote ${Object.keys(families).length} palettes, ${semantic.length} semantic tokens, ` +
    `${typography.length} text styles and ${shadows.length} shadows to src/styles/tokens.css`,
);
